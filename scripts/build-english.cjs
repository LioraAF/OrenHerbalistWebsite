// Generate the English public site from the Hebrew pages and reviewed translations.
// Keep structure and behavior shared; fail the build if new copy needs translating.
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const pages = ['index', 'treatment', 'products', 'workshops', 'videos'];
const scripts = ['main', 'drive-videos', 'contact'];
const headingScale = 1.21;
// Retain every heading's existing proportions and responsive breakpoints.
function scaleHeadingRules(source) {
  source = source.replace(/\/\*[\s\S]*?\*\//g, '');
  let result = '', cursor = 0;
  while (cursor < source.length) {
    const opening = source.indexOf('{', cursor);
    if (opening < 0) break;
    const selector = source.slice(cursor, opening).trim();
    let depth = 1, end = opening + 1, quote = '';
    for (; end < source.length && depth; end++) {
      const char = source[end];
      if (char === '\\') { end++; continue; }
      if (quote) { if (char === quote) quote = ''; continue; }
      if (char === '"' || char === "'") { quote = char; continue; }
      if (char === '{') depth++;
      if (char === '}') depth--;
    }
    const body = source.slice(opening + 1, end - 1);
    if (/^@(media|supports)\b/.test(selector)) {
      const nested = scaleHeadingRules(body);
      if (nested) result += `${selector} {\n${nested}}\n`;
    } else if (!selector.startsWith('@')) {
      const size = body.match(/(?:^|;)\s*font-size\s*:\s*([^;]+)/);
      const headings = selector.split(',').map(s => s.trim())
        .filter(s => /\bh[123]\b|\.reel-card-title\b/.test(s));
      if (size && headings.length) {
        // :where scopes shared rules without changing their original specificity.
        const scoped = headings.map(s => s.startsWith('html[lang="en"]')
          ? s : `:where(html[lang="en"]) ${s}`).join(',\n');
        result += `${scoped} { font-size: calc((${size[1].trim()}) * ${headingScale}); }\n`;
      }
    }
    cursor = end;
  }
  return result;
}
const headingStyles = '/* Generated by scripts/build-english.cjs; headings at 121% of their original sizes. */\n' +
  ['css/style.css', 'css/english.css'].map(file => scaleHeadingRules(fs.readFileSync(path.join(root, file), 'utf8'))).join('\n');
fs.mkdirSync(path.join(root, 'en/css'), { recursive: true });
fs.writeFileSync(path.join(root, 'en/css/heading-sizes.css'), headingStyles);
const headingStylesVersion = createHash('sha256').update(headingStyles).digest('hex').slice(0, 12);
const translations = JSON.parse(fs.readFileSync(path.join(root, 'translations/en.json'), 'utf8'));
const englishStylesVersion = createHash('sha256').update(fs.readFileSync(path.join(root, 'css/english.css'))).digest('hex').slice(0, 12);
const fontLinks = `  <link rel="preconnect" href="https://fonts.googleapis.com">\n  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Amatic+SC&amp;family=Assistant:wght@300&amp;family=Bellefair&amp;family=Cormorant+Garamond:wght@400;600;700&amp;family=Forum&amp;family=Oooh+Baby&amp;family=WindSong&amp;display=swap">\n`;
const hebrew = /[\u0590-\u05ff]/;
const normalize = (text) => text.replace(/\s+/g, ' ').trim();
function translate(text) {
  if (!hebrew.test(text)) return text;
  const key = normalize(text);
  if (!Object.hasOwn(translations, key)) throw new Error(`Missing English translation: ${key}`);
  return text.replace(text.trim(), translations[key]);
}
const escapeAttribute = (text) => text.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const escapeText = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
fs.mkdirSync(path.join(root, 'en/js'), { recursive: true });
for (const page of pages) {
  const source = fs.readFileSync(path.join(root, `${page}.html`), 'utf8');
  let html = source.replace(/<!--[^]*?-->|<[^>]+>|[^<]+/g, (part) => {
    if (part.startsWith('<!--')) return part;
    if (!part.startsWith('<')) {
      const copy = hebrew.test(part) ? escapeText(translate(part)) : part;
      return copy.replace(/₪/g, '<span class="currency-symbol">₪</span>');
    }
    return part.replace(/\b(alt|aria-label|content|placeholder|title)="([^"]*)"/g,
      (match, attr, value) => hebrew.test(value) ? `${attr}="${escapeAttribute(translate(value))}"` : match);
  });
  html = html.replace('lang="he" dir="rtl"', 'lang="en" dir="ltr"')
    .replace(/dir="rtl"/g, 'dir="ltr"')
    .replace(/(href|src)="(css\/|images\/)/g, '$1="../$2')
    .replace('src="js/gallery-images.js"', 'src="../js/gallery-images.js"')
    .replace(/(<link rel="alternate"[^>]+>\s*)/g, '')
    .replace(/<a class="language-switch"[^>]*>[^<]*<\/a>\s*/g, '')
    .replace('</head>', `${fontLinks}  <link rel="stylesheet" href="../css/english.css?v=${englishStylesVersion}">\n  <link rel="stylesheet" href="css/heading-sizes.css?v=${headingStylesVersion}">\n  <link rel="alternate" hreflang="he" href="../${page}.html">\n  <link rel="alternate" hreflang="en" href="${page}.html">\n</head>`)
    .replace('</header>', `  <a class="language-switch" href="../${page}.html" lang="he" hreflang="he" dir="rtl" aria-label="Switch to Hebrew">עברית</a>\n  </header>`);
  if (page === 'index') {
    html = html.replace(/(<div class="whatsapp-invitation">[\s\S]*?<\/ul>)/,
      '$1\n        <p class="whatsapp-language-note"><strong>Group content is in Hebrew.</strong></p>');
  }
  if (page === 'workshops') {
    html = html.replace(/(<article[^>]*data-workshop-modal="lecture"[^>]*>\s*<p class="workshop-label">)Talk(<\/p>)/,
      '$1Lecture$2');
  }
  if (page === 'videos') {
    html = html.replace('<p class="library-note">', '<p class="library-note">The videos are in Hebrew, with titles and descriptions in English.</p>\n          <p class="library-note library-disclaimer">');
  }
  fs.writeFileSync(path.join(root, `en/${page}.html`), html);
}
for (const name of scripts) {
  let source = fs.readFileSync(path.join(root, `js/${name}.js`), 'utf8');
  source = source.replace(/(["'`])((?:\\.|(?!\1)[^\\])*?)\1/gs, (literal, quote, value) => {
    if (!hebrew.test(value)) return literal;
    const english = translate(value);
    if (quote === '`') return '`' + english.replace(/`/g, '\\`') + '`';
    return JSON.stringify(english);
  }).replace(/(["'`])images\//g, '$1../images/')
    .replace('"css/feedback.css', '"../css/feedback.css')
    .replace('"js/feedback.js', '"../js/feedback.js');
  if (name === 'contact') source = source.replace('language: "he"', 'language: "en"');
  fs.writeFileSync(path.join(root, `en/js/${name}.js`), '// Generated by scripts/build-english.cjs. Edit shared JS or translations/en.json.\n' + source);
  const version = createHash('sha256').update(source).digest('hex').slice(0, 12);
  for (const page of pages) {
    const file = path.join(root, `en/${page}.html`);
    const html = fs.readFileSync(file, 'utf8').replace(
      new RegExp(`src="js/${name}\\.js[^\"]*"`, 'g'), `src="js/${name}.js?v=${version}"`);
    fs.writeFileSync(file, html);
  }
}
console.log('Generated five English pages and their translated scripts.');
